/**
 * Builds the second-annotator (double-label) sitting: a stratified, seeded
 * selection of already-labelled pages, re-presented through the SAME review
 * generator the first annotator used — and never through their verdicts.
 *
 * Why this exists. Every accuracy figure in the ledger sits on one
 * annotator's judgement, so every figure carries an unknown noise floor: the
 * rate at which two careful humans disagree about the same ink. Until that
 * rate is measured, "94.4%" has an error bar nobody can state. Re-labelling
 * a stratified slice with a second annotator buys that floor for one sitting.
 *
 * Independence (principles §8, the presentation question). This script reads
 * proposals.json only. It never opens gold-verdicts.json, so the generated
 * pages CANNOT contain the first annotator's verdicts. Auto-corroboration
 * marks are reproduced by re-running the current corroboration code against
 * the same run records — which is only "what annotator 1 saw" if that code
 * has not changed since their sitting. For batches labelled BEFORE the
 * current tokenizer/corroboration era the regenerated auto set DRIFTS (18
 * batch2 rows annotator 1 hand-judged regenerate as auto under today's
 * code), silently removing hand-judged rows from the agreement pool. Such
 * batches are listed in --plain and regenerate WITHOUT corroboration: the
 * second annotator hand-judges every row, annotator 1's human rows all stay
 * comparable, and annotator 1's original-era auto rows fall out of the pool
 * as machine-marked (they carry no human judgement to compare). The scorer
 * independently cross-checks auto status per row and reports any residual
 * mismatch as presentationDrift. A test asserts the generated pages are
 * free of verdict content.
 *
 * Selection is seeded and stratified per batch across derived page classes —
 * conflict (carries adjudications), clean (not escalated in the run), and
 * escalated-other — so the agreement number is not dominated by whichever
 * class a batch happens to be full of. Class here only balances the SAMPLE;
 * it is derived from the proposals the first annotator already saw, not from
 * anything computed after their sitting.
 *
 * Usage:
 *   node scripts/evaluation/build-gold-doublelabel.mjs \
 *     --gold-root .evaluation/gold \
 *     --batches pilot-v1,batch2-v1,batch3-v1,batch4-v1,batch5-clean-v1 \
 *     --output-dir .evaluation/gold/batch6-doublelabel-v1 \
 *     [--per-batch 4] [--seed 1] [--plain batch2-v1]
 *
 * --plain lists batches whose pages are regenerated WITHOUT corroboration
 * auto-marks regardless of what their original sitting used — required for
 * any batch labelled before the current corroboration code (see the
 * independence note above). Defaults to batch2-v1, the one batch verified
 * to drift. Pass --plain '' only if every batch is era-current.
 *
 * Output: per run-root group, a proposals-<n>.json subset plus a
 * review-<n>.html generated by build-gold-review.mjs, and a selection.json
 * recording the seed and the counts (never page text). The second annotator
 * works the review pages exactly like a normal batch and exports
 * gold-verdicts JSON per group; score-annotator-agreement.mjs then compares
 * the two annotators' files.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

function arg(name, fallback) {
  const index = process.argv.indexOf(name);
  if (index >= 0 && process.argv[index + 1]) return process.argv[index + 1];
  if (fallback !== undefined) return fallback;
  throw new Error(`Missing required argument ${name}`);
}

const goldRoot = arg('--gold-root');
const batches = arg('--batches').split(',').map((entry) => entry.trim()).filter(Boolean);
const outputDir = arg('--output-dir');
const perBatch = Number(arg('--per-batch', '4'));
const seed = Number(arg('--seed', '1'));
const plainBatches = new Set(arg('--plain', 'batch2-v1').split(',').map((entry) => entry.trim()).filter(Boolean));

// Deterministic shuffle — the same LCG as the spot-check, for the same
// reason: an agreement sample nobody can regenerate cannot be disputed.
let state = (seed * 1103515245 + 12345) >>> 0;
const nextRandom = () => {
  state = (state * 1103515245 + 12345) >>> 0;
  return state / 0x100000000;
};
function shuffle(items) {
  const shuffled = [...items];
  for (let i = shuffled.length - 1; i > 0; i -= 1) {
    const j = Math.floor(nextRandom() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

// Derived class, from information that predates annotator 1's sitting.
function pageClass(page) {
  if ((page.conflictAdjudications ?? []).length > 0) return 'conflict';
  if (page.escalatedInRun === false) return 'clean';
  return 'escalated-other';
}

const selected = [];
const countsByBatch = {};
// Whether a batch's FIRST sitting used native corroboration (silver
// auto-marking) is detected from its original review.html — presentation
// the first annotator saw, never their verdicts. The pilot predates silver;
// regenerating its pages WITH corroboration would show annotator 2 a page
// annotator 1 never saw, and auto-mark rows out of the agreement pool.
const corroborationUsed = new Map();
for (const batch of batches) {
  let reviewHtml = '';
  try { reviewHtml = readFileSync(join(goldRoot, batch, 'review.html'), 'utf8'); } catch { /* fall through: assume corroboration */ }
  corroborationUsed.set(batch, reviewHtml === '' || reviewHtml.includes('value="auto"'));
}
for (const batch of batches) {
  // Deliberately NOT reading gold-verdicts.json — see the header. Only the
  // proposals file, which is what the first annotator was shown.
  const proposals = JSON.parse(readFileSync(join(goldRoot, batch, 'proposals.json'), 'utf8'));
  const byClass = new Map();
  for (const page of proposals) {
    const cls = pageClass(page);
    if (!byClass.has(cls)) byClass.set(cls, []);
    byClass.get(cls).push(page);
  }
  for (const list of byClass.values()) shuffle(list).forEach((page, i) => { list[i] = page; });
  // Round-robin across classes so one class cannot fill the quota alone.
  const classes = shuffle([...byClass.keys()]);
  const picked = [];
  let cursor = 0;
  const offsets = new Map(classes.map((cls) => [cls, 0]));
  while (picked.length < Math.min(perBatch, proposals.length)) {
    const cls = classes[cursor % classes.length];
    cursor += 1;
    const offset = offsets.get(cls);
    const pool = byClass.get(cls);
    if (offset < pool.length) {
      picked.push({ batch, class: cls, page: pool[offset] });
      offsets.set(cls, offset + 1);
    }
    if (cursor > classes.length * (perBatch + proposals.length)) break;
  }
  countsByBatch[batch] = {};
  for (const entry of picked) countsByBatch[batch][entry.class] = (countsByBatch[batch][entry.class] ?? 0) + 1;
  selected.push(...picked);
}

if (!selected.length) throw new Error('Selection is empty.');
mkdirSync(outputDir, { recursive: true });

// Group by run root so corroboration (silver auto-marking) reproduces each
// batch's original presentation: same run records, same corroborate code,
// same auto set. A batch whose verdicts never used corroboration (the pilot
// era) is grouped under 'none' and generated without --run-root.
const groups = new Map();
for (const entry of selected) {
  const eraSafe = corroborationUsed.get(entry.batch) && !plainBatches.has(entry.batch);
  const runRoot = eraSafe ? (entry.page.provenance?.runRoot ?? 'none') : 'none';
  const key = runRoot !== 'none' && existsSync(runRoot) ? runRoot : 'none';
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(entry);
}

const generated = [];
let groupIndex = 0;
for (const [runRoot, entries] of groups) {
  groupIndex += 1;
  const proposalsPath = join(outputDir, `proposals-${groupIndex}.json`);
  const reviewPath = join(outputDir, `review-${groupIndex}.html`);
  writeFileSync(proposalsPath, JSON.stringify(entries.map((entry) => entry.page), null, 1));
  const args = [join(here, 'build-gold-review.mjs'), '--proposals', proposalsPath, '--output', reviewPath];
  if (runRoot !== 'none') args.push('--run-root', runRoot);
  execFileSync(process.execPath, args, { stdio: 'inherit' });
  generated.push({
    group: groupIndex,
    runRoot: runRoot === 'none' ? null : runRoot,
    pages: entries.length,
    batches: [...new Set(entries.map((entry) => entry.batch))],
    review: basename(reviewPath),
    proposals: basename(proposalsPath)
  });
}

const selection = {
  doubleLabelSchemaVersion: 'gold-doublelabel-v1',
  seed,
  perBatch,
  batches,
  plainBatches: [...plainBatches],
  pagesSelected: selected.length,
  countsByBatch,
  pages: selected.map((entry) => ({
    batch: entry.batch, class: entry.class,
    objectId: entry.page.objectId, pageNumber: entry.page.pageNumber, sha256: entry.page.sha256
  })),
  groups: generated
};
writeFileSync(join(outputDir, 'selection.json'), JSON.stringify(selection, null, 1));
console.log(`Selected ${selected.length} pages (seed ${seed}) into ${generated.length} review group(s) under ${outputDir}:`);
for (const [batch, counts] of Object.entries(countsByBatch)) {
  console.log(`  ${batch}: ${Object.entries(counts).map(([cls, count]) => `${cls}=${count}`).join(' ')}`);
}
